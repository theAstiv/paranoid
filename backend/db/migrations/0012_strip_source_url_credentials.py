"""Migration 0012 — code source hardening (BB-08, BB-19).

1. Strip ``user:password@`` / ``token@`` from stored ``code_sources.git_url``.
   ``validate_git_url`` now refuses such URLs, but older rows kept the credential
   in plain text and returned it from the API. When the row has no encrypted PAT
   yet the extracted token is encrypted into ``pat_ciphertext``; otherwise it is
   dropped. If stripping would collide with another source's ``(git_url, ref)``,
   the duplicate gets a ``#duplicate-<id>`` fragment and is marked failed so the
   user re-adds it.
2. Give sources with ``project_id IS NULL`` the Default Project (``POST /sources``
   did not store a project before this release).

Row ids and counts are logged, never the credential.

Do NOT edit this file after it has been applied to any production database.
"""

import logging
from datetime import UTC, datetime
from urllib.parse import urlsplit, urlunsplit

import aiosqlite

from backend.security import source_key


logger = logging.getLogger(__name__)

_DEFAULT_PROJECT_ID = "00000000-0000-0000-0000-000000000000"
_KEY_SOURCE_ROW = "pat_key_source"


# A bare ``https://<x>@host`` is either a token (``https://ghp_…@github.com``) or just a
# username (``https://alice@github.com``). Only treat it as a token when it carries a
# known token prefix; otherwise storing it as the PAT would make every clone fail.
_TOKEN_PREFIXES = ("ghp_", "gho_", "ghu_", "ghs_", "ghr_", "github_pat_", "glpat-")


def _split_credentials(url: str) -> tuple[str, str | None] | None:
    """Return ``(clean_url, token)`` for a URL with userinfo, else ``None``.

    ``token`` is the password of ``user:password@`` (the username is lost, which only
    matters to hosts like Bitbucket that need one), or a bare username that looks like
    a token. ``None`` means nothing worth storing.
    """
    parts = urlsplit(url)
    userinfo, sep, host = parts.netloc.rpartition("@")
    if not sep:
        return None
    user, has_password, password = userinfo.partition(":")
    if has_password:
        token = password or None
    else:
        token = user if user.startswith(_TOKEN_PREFIXES) else None
    return urlunsplit(parts._replace(netloc=host)), token


async def _encrypt_token(conn: aiosqlite.Connection, token: str) -> bytes | None:
    """Encrypt ``token`` under the active key, or ``None`` if that would be unsafe.

    Goes through ``conn`` for the key-source marker: the shared ``db`` connection
    is inside the runner's transaction here, so ``record_pat_key_source`` would
    deadlock.
    """
    try:
        active = source_key.key_source()
        ciphertext = source_key.encrypt_pat(token)
    except source_key.SourceKeyUnavailableError as exc:
        logger.warning("Migration 0012: no usable PAT key (%s); dropping credential", exc)
        return None

    async with conn.execute("SELECT value FROM config WHERE key = ?", (_KEY_SOURCE_ROW,)) as cur:
        row = await cur.fetchone()
    if row is None:
        await conn.execute(
            "INSERT OR IGNORE INTO config (key, value, encrypted, updated_at) VALUES (?, ?, 0, ?)",
            (_KEY_SOURCE_ROW, active.encode("utf-8"), datetime.now(UTC).isoformat()),
        )
    elif bytes(row[0]).decode("utf-8") != active:
        # Encrypting under a different key than the stored PATs would make this
        # one undecryptable (KeySourceChangedError on every clone).
        logger.warning("Migration 0012: PAT key source differs from the recorded one; dropping")
        return None
    return ciphertext


async def _strip_url_credentials(conn: aiosqlite.Connection) -> int:
    """Return how many rows had credentials removed from ``git_url``."""
    async with conn.execute("PRAGMA table_info(code_sources)") as cur:
        columns = {row[1] for row in await cur.fetchall()}
    if not {"pat_ciphertext", "last_index_status", "last_index_error"} <= columns:
        # A table this old predates stored PATs, so there is nothing to move.
        logger.warning("Migration 0012: code_sources has no PAT columns; skipping URL strip")
        return 0

    async with conn.execute(
        "SELECT id, git_url, pat_ciphertext FROM code_sources WHERE git_url LIKE '%@%'"
    ) as cur:
        candidates = await cur.fetchall()

    stripped = 0
    for source_id, git_url, pat_ciphertext in candidates:
        split = _split_credentials(git_url)
        if split is None:
            continue
        clean_url, token = split

        new_pat = None
        if pat_ciphertext is None and token:
            new_pat = await _encrypt_token(conn, token)
        outcome = (
            "kept existing PAT"
            if pat_ciphertext is not None
            else ("moved to PAT field" if new_pat is not None else "dropped")
        )

        try:
            await conn.execute(
                "UPDATE code_sources SET git_url = ?, pat_ciphertext = COALESCE(?, pat_ciphertext)"
                " WHERE id = ?",
                (clean_url, new_pat, source_id),
            )
        except aiosqlite.IntegrityError:
            await conn.execute(
                "UPDATE code_sources SET git_url = ?, pat_ciphertext = COALESCE(?, pat_ciphertext),"
                " last_index_status = 'failed', last_index_error = ? WHERE id = ?",
                (
                    f"{clean_url}#duplicate-{source_id}",
                    new_pat,
                    (
                        "Duplicate of an existing source after removing credentials from the "
                        "URL; delete it and re-add the source with the token in the PAT field."
                    ),
                    source_id,
                ),
            )
            outcome += ", renamed as duplicate"
        stripped += 1
        logger.info(
            "Migration 0012: stripped URL credentials from source %s (%s)", source_id, outcome
        )
    return stripped


async def up(conn: aiosqlite.Connection) -> None:
    """Must NOT call BEGIN or COMMIT — the runner owns the transaction."""
    stripped = await _strip_url_credentials(conn)
    cur = await conn.execute(
        "UPDATE code_sources SET project_id = ? WHERE project_id IS NULL", (_DEFAULT_PROJECT_ID,)
    )
    logger.info(
        "Migration 0012: %d source URL(s) stripped, %d source(s) moved to the Default Project",
        stripped,
        cur.rowcount,
    )
