"""Migration 0013 — component IDs for flows, trust boundaries and threats (B1, #13).

Adds nullable asset links, so a flow endpoint, a trust-boundary endpoint or a
threat target can point at the `assets` row it names:
- flows.source_asset_id / target_asset_id
- trust_boundaries.source_asset_id / target_asset_id
- threats.target_asset_id

All are `REFERENCES assets(id) ON DELETE SET NULL`: deleting an asset degrades
a link to the original free text rather than removing the flow or threat. The
text columns stay authoritative; the links are derived by
backend.pipeline.nodes.entities and filled in by backend.db.component_links
(on every save and once at startup for rows that predate this migration), never
by the LLM.

Columns and indexes only — existing rows read back NULL. No data is rewritten
here so the migration can't depend on resolver code that is still evolving.

Do NOT edit this file after it has been applied to any production database.
"""

import logging

import aiosqlite


logger = logging.getLogger(__name__)

_COLUMNS = (
    ("flows", "source_asset_id"),
    ("flows", "target_asset_id"),
    ("trust_boundaries", "source_asset_id"),
    ("trust_boundaries", "target_asset_id"),
    ("threats", "target_asset_id"),
)


async def up(conn: aiosqlite.Connection) -> None:
    for table, column in _COLUMNS:
        ddl = (
            f"ALTER TABLE {table} ADD COLUMN {column} TEXT REFERENCES assets(id) ON DELETE SET NULL"
        )
        try:
            await conn.execute(ddl)
        except aiosqlite.OperationalError as exc:
            if "duplicate column name" not in str(exc).lower():
                raise
            logger.debug("Column %s.%s already exists, skipping", table, column)
        await conn.execute(f"CREATE INDEX IF NOT EXISTS idx_{table}_{column} ON {table}({column})")
